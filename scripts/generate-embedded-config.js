const fs = require("fs");
const path = require("path");
const dotenv = require("dotenv");

const ROOT_DIR = path.resolve(__dirname, "..");
const ENV_PATH = path.join(ROOT_DIR, ".env");
const OUTPUT_PATH = path.join(ROOT_DIR, "src", "generated-embedded-config.js");
const DEFAULT_BASE_URL = "https://onebs.onetech.al:9956/BC23_BS/ODataV4/Company('BESTSELLER')";

if (!fs.existsSync(ENV_PATH)) {
  throw new Error(`Missing .env file at ${ENV_PATH}.`);
}

const parsedEnv = dotenv.parse(fs.readFileSync(ENV_PATH));
const embeddedConfig = {
  bcBaseUrl: parsedEnv.BC_BASE_URL || DEFAULT_BASE_URL,
  bcUsername: parsedEnv.BC_USERNAME || "",
  bcPassword: parsedEnv.BC_PASSWORD || "",
  accountNo: parsedEnv.BC_LEDGER_ACCOUNT_NO || "4092",
  timeoutMs: Number(parsedEnv.BC_TIMEOUT_MS || 45000),
};

if (!embeddedConfig.bcUsername || !embeddedConfig.bcPassword) {
  throw new Error("BC_USERNAME and BC_PASSWORD are required in .env before generating embedded config.");
}

const fileContents = `${[
  "// Generated by scripts/generate-embedded-config.js. Do not edit manually.",
  "module.exports = {",
  `  bcBaseUrl: ${JSON.stringify(embeddedConfig.bcBaseUrl)},`,
  `  bcUsername: ${JSON.stringify(embeddedConfig.bcUsername)},`,
  `  bcPassword: ${JSON.stringify(embeddedConfig.bcPassword)},`,
  `  accountNo: ${JSON.stringify(embeddedConfig.accountNo)},`,
  `  timeoutMs: ${JSON.stringify(embeddedConfig.timeoutMs)},`,
  "};",
].join("\n")}\n`;

fs.writeFileSync(OUTPUT_PATH, fileContents, "utf8");
console.log(`Embedded config written to ${OUTPUT_PATH}`);
